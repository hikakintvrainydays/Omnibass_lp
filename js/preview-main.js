function setLang(lang) {
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        }
    });

    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.remove('active');
    });
    if (lang === 'ja') document.querySelectorAll('.lang-btn')[0].classList.add('active');
    else document.querySelectorAll('.lang-btn')[1].classList.add('active');
}

// Streamline River Scroll Animation
function initStreamlineAnimation() {
    const riverPath = document.getElementById('river-path');
    const streamlineSection = document.getElementById('services');
    const nodes = document.querySelectorAll('.step-node');

    if (!riverPath || !streamlineSection) return;

    // IntersectionObserverでセクションが画面に入ったらアニメーション開始
    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                // 川のパスを描画（stroke-dashoffsetを0に） - 4秒でゆっくり
                riverPath.style.transition = 'stroke-dashoffset 4s cubic-bezier(0.4, 0, 0.2, 1)';
                riverPath.style.strokeDashoffset = '0';

                // ノードを順番にフェードイン + スケールアニメーション
                nodes.forEach((node, index) => {
                    setTimeout(() => {
                        node.style.transition = 'opacity 0.8s ease-out, transform 0.8s cubic-bezier(0.34, 1.56, 0.64, 1)';
                        node.style.opacity = '1';
                        node.style.transform = 'scale(1.2)';
                        // 少し縮んで落ち着く
                        setTimeout(() => {
                            node.style.transform = 'scale(1)';
                        }, 400);
                    }, 1000 + (index * 800));
                });
            }
        });
    }, { threshold: 0.3 });

    observer.observe(streamlineSection);
}

// 初期化
document.addEventListener('DOMContentLoaded', () => {
    initStreamlineAnimation();
    initWaterStreamAnimation();
});

// 水のラインの高度なスクロール連動アニメーション
function initWaterStreamAnimation() {
    const serviceSection = document.getElementById('services');
    const mainPath = document.querySelector('.stream-path.stream-main');
    const particles = document.querySelectorAll('.particle');

    if (!serviceSection || !mainPath) return;

    // 初期状態: パーティクル非表示
    particles.forEach(p => {
        p.style.opacity = '0';
    });

    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                // メインラインの描画アニメーション開始
                mainPath.classList.add('animate');

                // パーティクルを順番に表示
                particles.forEach((particle, index) => {
                    setTimeout(() => {
                        particle.style.transition = 'opacity 0.8s ease-out';
                        particle.style.opacity = particle.getAttribute('opacity') || '0.8';
                    }, 800 + (index * 400));
                });

                // 一度発動したら監視終了
                observer.disconnect();
            }
        });
    }, { threshold: 0.15 });

    observer.observe(serviceSection);
}

// Hikone Castle Scroll Trigger
function checkCastleVisible() {
    const castle = document.getElementById('hikone-castle');
    const caption = document.getElementById('castle-caption');
    const container = document.getElementById('castle-container');

    if (!container) return;

    const rect = container.getBoundingClientRect();
    const windowHeight = window.innerHeight;

    // Trigger when castle container is 80% visible
    if (rect.top < windowHeight * 0.8) {
        castle.classList.add('built');
        caption.classList.add('visible');
    }
}

window.addEventListener('scroll', checkCastleVisible);
window.addEventListener('load', checkCastleVisible);
